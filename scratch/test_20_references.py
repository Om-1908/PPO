def build_qiskit_circuit(actions, n_qubits=2):
    qc = QuantumCircuit(n_qubits)
    for g, q, a in actions:
        if g == 'H': qc.h(q)
        elif g == 'X': qc.x(q)
        elif g == 'Y': qc.y(q)
        elif g == 'Z': qc.z(q)
        elif g == 'S': qc.s(q)
        elif g == 'Sdg': qc.sdg(q)
        elif g == 'T': qc.t(q)
        elif g == 'Tdg': qc.tdg(q)
        elif g == 'RX': qc.rx(a, q)
        elif g == 'RY': qc.ry(a, q)
        elif g == 'RZ': qc.rz(a, q)
        elif g == 'CNOT':
            if isinstance(q, (tuple, list)):
                ctrl, tgt = q
            else:
                ctrl, tgt = 0, 1
            qc.cx(ctrl, tgt)
        elif g == 'CZ': qc.cz(0, 1)
        elif g == 'SWAP': qc.swap(0, 1)
    return qc

